// The registers probe_campaign_regs reads as the boot left them. Owner: the silicon evidence
// campaign (specs/notes/silicon-campaign.md). MIT.
//
// One entry per register of every class C row of specs/blocks/*.toml that the campaign's
// first-touch ledger shows a corpus image reaching and whose value a plain read can observe, plus
// the two TIMG0 calibration registers specs/oracle-known-diffs.toml names reset values for. Each
// entry is {row id, fact, address}: the row id is `<block>.<register or glob>` as the inventory
// spells it, the fact is `<block>.<register>`, and the address is the block base of
// crates/pemu-soc-c3/src/periph/mod.rs (`c3_devices!`) plus the offset of specs/c3-registers.csv.
// Rows with `offsets` (regi2c) name the offset instead of a register. Written from those two files
// by a script, not by hand; a register the CSV does not have cannot appear here.
//
// No register below has a read-clear field (the CSV's access column carries no RC for any of
// them), so reading them changes nothing.

