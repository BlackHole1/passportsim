//! The Markdown surfaces: `docs/commands/<name>.md`, `docs/commands/index.md` and
//! `docs/errors.md`.
//!
//! Host availability is a column read from `pemu_api::host_support::TABLE`, never a filter, so
//! the committed text is byte-identical on macOS, on Windows and in a browser build.

use pemu_api::error::{self, ErrorCode};
use pemu_api::spec::CapsGroup;
use serde_json::Value;

use super::mcp;
use super::model::{Command, HOSTS, annotation_names};

/// First line of every generated Markdown file.
pub const HEADER: &str = "<!-- generated by `cargo xtask docs`; do not edit. -->";

/// `yes` or `no` in a host column.
fn yes_no(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

/// `docs/commands/<name>.md`: the reference page of one command.
pub fn command_page(command: &Command) -> String {
    let spec = command.spec;
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");
    out.push_str(&format!("# `passportsim {}`\n\n", spec.name));
    out.push_str(&format!("{}\n\n", spec.summary));

    out.push_str("| Property | Value |\n|---|---|\n");
    out.push_str(&format!("| Caps group | `{}` |\n", spec.group.caps_name()));
    out.push_str(&format!("| MCP tool | `{}` |\n", command.mcp_tool()));
    out.push_str(&format!("| HTTP route | `{}` |\n", command.http_route()));
    out.push_str(&format!(
        "| Scenario step | {} |\n",
        spec.scenario_step
            .map(|s| format!("`{s}`"))
            .unwrap_or_else(|| "none".to_string())
    ));
    out.push_str(&format!(
        "| CLI aliases | {} |\n",
        list_or_none(spec.cli.aliases)
    ));
    out.push_str(&format!(
        "| Annotations | {} |\n",
        list_or_none(&annotation_names(spec))
    ));
    out.push('\n');

    out.push_str("## Hosts\n\n");
    out.push_str(
        "The matrix below is the full one; this page is byte-identical on every host.\n\n",
    );
    out.push_str("| macOS | Windows | Browser |\n|---|---|---|\n");
    out.push_str(&format!(
        "| {} | {} | {} |\n",
        yes_no(command.hosts.macos),
        yes_no(command.hosts.windows),
        yes_no(command.hosts.browser)
    ));
    if let Some(hint) = pemu_api::host_support::hint(spec.name) {
        out.push_str(&format!(
            "\nWhere it does not run, `E_HOST_UNSUPPORTED` names the alternative: {hint}\n"
        ));
    }
    out.push('\n');

    out.push_str("## Synopsis\n\n");
    out.push_str("```text\n");
    out.push_str(&synopsis(command));
    out.push_str("\n```\n\n");

    out.push_str("## Arguments\n\n");
    out.push_str(&arguments_table(command));
    out.push_str(&format!(
        "\nInput schema: [`docs/schema/commands/{}.input.json`](../schema/commands/{}.input.json).\n\n",
        spec.name, spec.name
    ));

    out.push_str("## Output\n\n");
    out.push_str(&format!(
        "Output schema: [`docs/schema/commands/{}.output.json`](../schema/commands/{}.output.json).\n",
        spec.name, spec.name
    ));
    out.push_str(&format!(
        "TypeScript types: `web/src/gen/commands/{}.d.ts` (`{}`, `{}`).\n\n",
        spec.name,
        command.ts_args(),
        command.ts_result()
    ));

    out.push_str("## Errors\n\n");
    if spec.errors.is_empty() {
        out.push_str("This command registers no error code of its own.\n\n");
    } else {
        out.push_str("| Code | Number |\n|---|---|\n");
        let mut codes: Vec<ErrorCode> = spec.errors.to_vec();
        codes.sort_by_key(|code| code.number);
        for code in codes {
            out.push_str(&format!("| `{}` | {} |\n", code.name, code.number));
        }
        out.push_str("\nEvery code is listed in [`docs/errors.md`](../errors.md).\n\n");
    }

    out.push_str("## Examples\n\n");
    for example in spec.examples {
        out.push_str(&format!("### {}\n\n", example.title));
        out.push_str(&example_blocks(command, example.args));
    }
    out
}

/// `skills/passportsim/references/commands/<name>.md`: the page of one command as the skill
/// carries it. It is [`command_page`] without the links that leave the skill directory (schemas,
/// TypeScript types, the repository's error page) and without the HTTP route, so an installed
/// skill is complete on its own.
pub fn skill_command_page(command: &Command) -> String {
    let spec = command.spec;
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");
    out.push_str(&format!("# `passportsim {}`\n\n", spec.name));
    out.push_str(&format!("{}\n\n", spec.summary));
    out.push_str("| MCP tool | Scenario step | macOS | Windows | Browser |\n");
    out.push_str("|---|---|---|---|---|\n");
    out.push_str(&format!(
        "| `{}` | {} | {} | {} | {} |\n",
        command.mcp_tool(),
        spec.scenario_step
            .map(|s| format!("`{s}`"))
            .unwrap_or_else(|| "none".to_string()),
        yes_no(command.hosts.macos),
        yes_no(command.hosts.windows),
        yes_no(command.hosts.browser)
    ));
    if let Some(hint) = pemu_api::host_support::hint(spec.name) {
        out.push_str(&format!(
            "\nWhere it does not run, `E_HOST_UNSUPPORTED` names the alternative: {hint}\n"
        ));
    }
    out.push('\n');

    out.push_str("## Synopsis\n\n```text\n");
    out.push_str(&synopsis(command));
    out.push_str("\n```\n\n");

    out.push_str("## Arguments\n\n");
    out.push_str(&arguments_table(command));
    out.push('\n');

    out.push_str("## Errors\n\n");
    if spec.errors.is_empty() {
        out.push_str("This command registers no error code of its own.\n\n");
    } else {
        let mut codes: Vec<ErrorCode> = spec.errors.to_vec();
        codes.sort_by_key(|code| code.number);
        let names: Vec<String> = codes
            .iter()
            .map(|code| format!("`{}` ({})", code.name, code.number))
            .collect();
        out.push_str(&names.join(", "));
        out.push_str(". What each means: [errors.md](../errors.md).\n\n");
    }

    out.push_str("## Examples\n\n");
    for example in spec.examples {
        out.push_str(&format!("### {}\n\n", example.title));
        out.push_str(&example_blocks(command, example.args));
    }
    out
}

