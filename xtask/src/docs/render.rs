/// `docs/errors.md`: every registered error code by group range.
///
/// An aggregate build output, not committed.
pub fn errors_page(commands: &[Command]) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n# Error codes\n\n");
    out.push_str(
        "Every command failure is a typed envelope: a registered code, a message, \
         the virtual time, a retryable flag and an optional hint. Codes are registered per caps \
         group, each group holding one number range; a shipped name and number never change or \
         get reused.\n\n",
    );
    out.push_str(
        "The envelope schema is [`docs/schema/error@1.json`](schema/error@1.json). The wasm ABI \
         reports the number as its result status, and 0 means success, so 0 is not a code.\n\n",
    );

    for group in CapsGroup::ALL {
        let range = group.error_range();
        out.push_str(&format!(
            "## `{}` ({}..={})\n\n",
            group.caps_name(),
            range.start(),
            range.end()
        ));
        let mut codes: Vec<ErrorCode> = error::registered_error_codes()
            .into_iter()
            .filter(|code| code.group() == Some(group))
            .collect();
        codes.sort_by_key(|code| code.number);
        codes.dedup_by_key(|code| code.number);
        if codes.is_empty() {
            out.push_str("No code is registered in this range yet.\n\n");
            continue;
        }
        out.push_str("| Code | Number | Meaning | Registered by |\n|---|---:|---|---|\n");
        for code in codes {
            let mut users: Vec<&str> = commands
                .iter()
                .filter(|command| command.spec.errors.contains(&code))
                .map(|command| command.spec.name)
                .collect();
            users.sort_unstable();
            users.dedup();
            let by = if users.is_empty() {
                "pre-registered".to_string()
            } else {
                users
                    .iter()
                    .map(|name| format!("`{name}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            // The sentence is `pemu_api::error`'s, beside the number, so this file cannot drift
            // from the registry it renders (the `error_codes!` table is the source of truth).
            let meaning = one_line(code.meaning());
            out.push_str(&format!(
                "| `{}` | {} | {meaning} | {by} |\n",
                code.name, code.number
            ));
        }
        out.push('\n');
    }
    out
}
