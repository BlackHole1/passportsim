//! `cargo xtask codegen`: spec tables and generated sources.
//!
//! - `codegen [--check]` turns `specs/irq-sources.toml`, `specs/c3-registers.csv` and
//!   `specs/blocks/` into `crates/pemu-core/src/irq_source.rs`, `gen/regs_<block>.rs`,
//!   `gen/mod.rs`, `gen/waits.rs`, `gen/classes.rs` and the `docs/fidelity.md` ledger; `--check`
//!   fails on a stale file.
//! - `codegen blob-symbols [--idf <dir>] [--check]` rebuilds `specs/hle/idf-5.5.3/blob-symbols.txt`
//!   from the IDF blob archives; the first form only verifies it.
//! - `codegen import [--idf <dir>] [--check]` rebuilds the CSV and the IRQ table from IDF v5.5.3.
//!   Both are run by hand when an input changes: their inputs live outside the repository, so CI
//!   tiers run only the first form.
//!
//! Generated tests: per block `table_is_consistent`, `fields_decode` and, through `RegStore`,
//! `resets_restore_the_table` and `access_types_behave`; `anchors` checks 13 IDF header resets,
//! the one check not derived from the CSV; `layout` the GDMA and MMU cross-checks. Columns and
//! block schema: `specs/README.md` sections 2, 3. Import rules:
//! - Access (`access.rs`): TRM Glossary types map exactly; any other string is `UNVERIFIED`.
//! - Reset scopes use the terms of IDF `soc/reset_reasons.h`: `System` also resets the RTC
//!   sub-system, `Core` resets the digital system without it. The SENSITIVE lock rule and values
//!   that are no header default are `specs/blocks/` rows.
//! - No readable field layout, so no rows: `iomux` (`io_mux_reg.h`), radio (`nrx_reg.h`), `regi2c`,
//!   `twai` (`twai_struct.h` only, no `twai_reg.h`), crypto (`soc/hwcrypto_reg.h`), and `mmu`,
//!   `dedicated_gpio`, `world_cntl` (a base in `reg_base.h` only).
//! - Header fixes (`idf.rs`), named in `note`: `_S`/`_V` macros beat a bitpos comment
//!   (`usb_serial_jtag_reg.h`, `usb_serial_jtag_struct.h` agrees); `syscon_reg.h` aliases skipped.

